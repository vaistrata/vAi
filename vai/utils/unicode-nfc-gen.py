"""Generates unicode-nfc.h, the tables the tokenizer's NFC normalizer reads.

    python vai/utils/unicode-nfc-gen.py

The data comes from Python's unicodedata, so the Unicode version is the running
Python's; the header records it. Hangul syllables are left out: their
decomposition and composition are arithmetic.
"""

import os
import unicodedata

HANGUL = range(0xAC00, 0xD7A4)


def canonical_decomposition(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):   # none, or a compatibility mapping NFC ignores
        return None
    return [int(x, 16) for x in d.split()]


def main():
    decompositions = {}    # cp -> one level of its canonical decomposition, 1 or 2 code points
    for cp in range(0x110000):
        if cp in HANGUL:
            continue
        parts = canonical_decomposition(cp)
        if parts:
            assert len(parts) <= 2
            decompositions[cp] = parts

    # A pair recomposes unless the character is a composition exclusion, a
    # singleton or a non-starter decomposition: exactly when NFC of the pair gives it back.
    ordered = sorted(decompositions)
    compositions = [
        i for i, cp in enumerate(ordered)
        if len(decompositions[cp]) == 2
        and unicodedata.normalize("NFC", chr(decompositions[cp][0]) + chr(decompositions[cp][1])) == chr(cp)
    ]
    compositions.sort(key=lambda i: tuple(decompositions[ordered[i]]))
    assert len(ordered) < 1 << 16

    classes = []           # [lo, hi, class], runs of one non-zero class
    for cp in range(0x110000):
        c = unicodedata.combining(chr(cp))
        if not c:
            continue
        if classes and classes[-1][1] == cp - 1 and classes[-1][2] == c:
            classes[-1][1] = cp
        else:
            classes.append([cp, cp, c])

    # Class-0 characters that still compose with the starter before them.
    composing_starters = sorted({
        decompositions[ordered[i]][1] for i in compositions
        if unicodedata.combining(chr(decompositions[ordered[i]][1])) == 0
    })

    def rows(values, per_line, fmt):
        return "\n".join(
            "    " + " ".join(fmt(v) + "," for v in values[i:i + per_line])
            for i in range(0, len(values), per_line))

    packed_decompositions = []
    for cp in ordered:
        parts = decompositions[cp] + [0]
        packed_decompositions.append(cp << 42 | parts[0] << 21 | parts[1])
    packed_classes = [lo << 42 | hi << 21 | c for lo, hi, c in classes]

    header = f"""// Generated by unicode-nfc-gen.py from Unicode {unicodedata.unidata_version}. Do not edit.

#ifndef VAI_UTILS_UNICODE_NFC_H
#define VAI_UTILS_UNICODE_NFC_H

#include <cstdint>

namespace vai::utils::unicode_nfc {{

// Every table packs 21-bit code points into a uint64_t, the highest field first,
// so each sorts as plain integers.

// Canonical decompositions, one level each, by code point: cp << 42 | first << 21
// | second, second 0 for a singleton. Hangul syllables are arithmetic, not here.
inline constexpr uint64_t kDecompositions[] = {{
{rows(packed_decompositions, 4, lambda v: f"0x{v:016X}")}
}};

// The kDecompositions entries whose pair recomposes, by (first, second).
inline constexpr uint16_t kCompositions[] = {{
{rows(compositions, 12, lambda v: f"{v:4d}")}
}};

// Runs of one non-zero canonical combining class: lo << 42 | hi << 21 | class.
inline constexpr uint64_t kCombiningClasses[] = {{
{rows(packed_classes, 4, lambda v: f"0x{v:016X}")}
}};

// Class-0 characters that compose with the starter before them.
inline constexpr uint32_t kComposingStarters[] = {{
{rows(composing_starters, 8, lambda v: f"0x{v:05X}")}
}};

}}   // namespace vai::utils::unicode_nfc

#endif   // VAI_UTILS_UNICODE_NFC_H
"""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "unicode-nfc.h")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)


if __name__ == "__main__":
    main()
